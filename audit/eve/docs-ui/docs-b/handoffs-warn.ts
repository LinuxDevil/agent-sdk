import { createAgent } from '@lousho/build-ai-agent';
import { mockModel } from '@lousho/build-ai-agent/testing';
const warns: string[] = [];
const ow = console.warn; console.warn = (...a: any[]) => warns.push(a.join(' '));
const target = createAgent({ name: 'billing', description: 'd', provider: mockModel(['x']), approve: () => true } as any);
const lead = createAgent({ name: 't', provider: mockModel(['hi']), handoffs: [target] });
console.log('after createAgent warns:', warns.length);
await lead.send('x');
console.log('after first send warns:', warns.length, warns[0]?.slice(0, 140));
console.warn = ow;
