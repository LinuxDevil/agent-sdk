import { describe, expect, it } from 'vitest';
import * as ts from 'typescript';
import type { AgentSpecV2 } from '../v2/types';
import { specToCode } from './typescript';

function spec(overrides: Partial<AgentSpecV2> = {}): AgentSpecV2 {
  return { version: 2, name: 'a', model: 'mock/m', instructions: 'You are a test agent.', ...overrides };
}

const minimal = spec();

/** A spec touching every section specToCode renders (S16b's full-section spec, inline). */
const full = spec({
  description: 'Does everything.',
  fallbackModels: ['mock/f1', 'mock/f2'],
  promptRef: 'support@prod',
  modelSettings: { maxTokens: 64, temperature: 0.2 },
  reasoning: 'low',
  tools: [{ builtin: 'current_date' }, { hosted: 'web_search' }],
  mcpServers: {
    docs: { url: 'https://x.test/mcp', headers: { Authorization: { env: 'HDR' }, 'X-Key': { secret: 'tok' } } },
  },
  skills: [{ inline: { name: 'changelog', description: 'Write changelogs.', content: '# C' } }],
  memory: [
    {
      name: 'notes',
      scope: 'session',
      provider: { type: 'in-memory' },
      itemJsonSchema: { type: 'object', properties: { text: { type: 'string' } } },
      itemKey: 'text',
    },
  ],
  subagents: {
    helper: { inline: { name: 'helper', model: 'mock/m', instructions: 'Help.', description: 'Helps.' } },
  },
  subagentOptions: { maxConcurrent: 2 },
  maxSubagentDepth: 2,
  handoffs: [{ agent: 'helper', description: 'Go helper.' }],
  maxHandoffs: 4,
  guardrails: [{ id: 'g1', name: 'deny-topics', on: 'input', options: { topics: ['weapons'] } }],
  permissions: [{ id: 'p1', tool: '*', action: 'allow' }],
  permissionMode: 'plan',
  approvalTtlMs: 60_000,
  askQuestion: true,
  hooks: [{ id: 'h1', inline: { name: 'noop', point: 'postGenerate', code: 'return;' } }],
  output: { jsonSchema: { type: 'object', properties: { city: { type: 'string' } }, required: ['city'] } },
  limits: { maxSteps: 7 },
  maxSteps: 9,
  compaction: { thresholdPercent: 0.5 },
  retry: { maxRetries: 4, backoff: { initialMs: 10 } },
  rateLimit: { requestsPerMinute: 12 },
  promptCaching: 'auto',
  toolSearch: { maxResults: 3 },
  codeMode: { timeoutMs: 1000 },
  triggers: [{ id: 't1', type: 'chat' }],
});

/** Instructions carrying a backtick, a `${x}` interpolation lookalike and a real newline. */
const trickyInstructions = 'Line one `tick` ${notAVar}\nLine two \\ backslash';
const tricky = spec({ instructions: trickyInstructions });
const fileInstructions = spec({ instructions: { file: 'prompts/main.md' } });

/** The import lines the generated module prints, in order. */
function importLines(code: string): string[] {
  return code.split('\n').filter((line) => line.startsWith('import '));
}

describe('specToCode', () => {
  it('renders a minimal spec as the header, host line and a createAgent call', () => {
    expect(specToCode(minimal)).toMatchInlineSnapshot(`
      "// Generated by lousho from AgentSpec v2 'a'. Edit the spec, not this file.
      import path from 'node:path';
      import { fileURLToPath } from 'node:url';
      import { createAgent } from 'lousho';

      /** Where relative paths in the spec start, and how named secrets resolve (environment variables here). */
      const host = { baseDir: path.dirname(fileURLToPath(import.meta.url)), resolveSecret: (name: string) => process.env[name] };

      export const agent = createAgent({
        name: 'a',
        model: 'mock/m',
        instructions: \`You are a test agent.\`,
      });
      "
    `);
  });

  it('renders a spec with every section', () => {
    expect(specToCode(full)).toMatchSnapshot();
  });

  it('is deterministic and follows KEY_ORDER regardless of input key order', () => {
    const shuffled = {
      version: 2,
      limits: { maxSteps: 7 },
      tools: [{ builtin: 'current_date' }],
      description: 'Shuffled.',
      instructions: 'You are a test agent.',
      model: 'mock/m',
      name: 'a',
    } as AgentSpecV2;
    const ordered = spec({ description: 'Shuffled.', tools: [{ builtin: 'current_date' }], limits: { maxSteps: 7 } });
    const code = specToCode(shuffled);
    expect(code).toBe(specToCode(shuffled));
    expect(code).toBe(specToCode(ordered));
    const optionIndex = (key: string) => code.indexOf(`\n  ${key}:`);
    expect(optionIndex('name')).toBeGreaterThanOrEqual(0);
    expect(optionIndex('name')).toBeLessThan(optionIndex('description'));
    expect(optionIndex('description')).toBeLessThan(optionIndex('model'));
    expect(optionIndex('model')).toBeLessThan(optionIndex('tools'));
    expect(optionIndex('tools')).toBeLessThan(optionIndex('limits'));
  });

  it('imports only the resolvers the spec uses', () => {
    const code = specToCode(spec({ tools: [{ builtin: 'current_date' }] }));
    expect(importLines(code)).toEqual([
      "import path from 'node:path';",
      "import { fileURLToPath } from 'node:url';",
      "import { createAgent, resolveToolRef } from 'lousho';",
    ]);
  });

  it('renders instructions as a template literal that evaluates to the original text', () => {
    const code = specToCode(tricky);
    const start = code.indexOf('instructions: `') + 'instructions: `'.length;
    const end = code.lastIndexOf('`,\n});');
    expect(start).toBeGreaterThanOrEqual('instructions: `'.length);
    expect(end).toBeGreaterThan(start);
    const body = code.slice(start, end);
    const evaluated = new Function(`return \`${body}\`;`)() as string;
    expect(evaluated).toBe(trickyInstructions);
  });

  it("imports readFile for { file } instructions and reads under host.baseDir", () => {
    const code = specToCode(fileInstructions);
    expect(importLines(code)[0]).toBe("import { readFile } from 'node:fs/promises';");
    expect(code).toContain("instructions: await readFile(path.join(host.baseDir, 'prompts/main.md'), 'utf8')");
  });

  it('appends the instructionsByFamily tail matching the model and skips it otherwise', () => {
    const matching = specToCode(
      spec({ model: 'mock/claude-x', instructions: 'Base.', instructionsByFamily: { claude: 'Claude tail.' } })
    );
    expect(matching).toContain('instructions: `Base.\nClaude tail.`');
    const other = specToCode(spec({ model: 'mock/m', instructions: 'Base.', instructionsByFamily: { claude: 'Claude tail.' } }));
    expect(other).toContain('instructions: `Base.`');
  });

  it('resolves handoffs to spec subagents through a subagents const and the host resolver', () => {
    const code = specToCode(
      spec({
        subagents: { helper: { inline: { name: 'helper', model: 'mock/m', instructions: 'Help.', description: 'Helps.' } } },
        handoffs: [{ agent: 'helper' }],
      })
    );
    expect(code).toContain('resolveHandoffAgent: async (name: string) => subagents[name]');
    expect(code).toContain('const subagents = {');
    expect(code).toContain('\n  subagents,\n');
  });

  it('renders a throwing resolveHandoffAgent when a handoff target is not defined in the file', () => {
    const code = specToCode(spec({ handoffs: [{ agent: 'ext' }] }));
    expect(code).toContain("throw new Error(`handoff target '${name}' is not defined in this file`)");
  });

  it('ends with a commented spec export when the spec carries triggers', () => {
    const code = specToCode(spec({ triggers: [{ id: 't1', type: 'chat' }] }));
    expect(code).toContain('// triggers, abortListeners, flow and evals are run by lousho dev / Studio, not by createAgent():');
    expect(code.trimEnd().endsWith("export const spec = { triggers: [{ id: 't1', type: 'chat' }] } as const;")).toBe(true);
  });

  it('honours options.packageName for the SDK import', () => {
    const code = specToCode(minimal, { packageName: '@scope/sdk' });
    expect(importLines(code)).toContain("import { createAgent } from '@scope/sdk';");
  });

  it.each([
    ['minimal', minimal],
    ['full', full],
    ['tricky instructions', tricky],
    ['file instructions', fileInstructions],
  ])('generates a module with no syntax diagnostics (%s)', (_label, input) => {
    const result = ts.transpileModule(specToCode(input), {
      reportDiagnostics: true,
      compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 },
    });
    expect(result.diagnostics ?? []).toEqual([]);
  });
});
