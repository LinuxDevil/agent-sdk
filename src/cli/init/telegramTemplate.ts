function readme(config: ProjectConfig, bot: BotOptions): string {
  const pm = config.packageManager;
  const info = providerInfo(config.provider);
  const run = (s: string) => `${pm} run ${s}`;
  const tokenSet = bot.token ? ' (token already in .env)' : '';
  return `# ${config.name}

${(bot.persona ?? 'A Telegram bot').trim()} — built with [lousho](https://github.com/LinuxDevil/agent-sdk).

## Next 3 commands

\`\`\`bash
${run('dev')}          # chat with the agent in your terminal first
${run('test')}         # offline tests, no API key needed
${run('telegram')}     # long-poll Telegram as @${bot.username ?? 'your_bot'}${tokenSet}
\`\`\`

## Telegram setup

1. @BotFather → \`/newbot\` → put the token in \`.env\` as \`TELEGRAM_BOT_TOKEN\`${tokenSet ? ' (done)' : ''}
2. Set \`BOT_USERNAME\` to the bot's handle (no @) so group mentions work
3. \`${run('telegram')}\` — then message the bot. **The first chat locks as the owner.**
4. Friends: add their chat IDs to \`ALLOWED_CHATS\` (have them message the bot; the log prints \`ignored message from non-owner chat <id>\`), or add the bot to a group with \`ALLOW_GROUPS=true\` — it answers @mentions and replies only.

## What is here

- \`src/agent.ts\` — the agent: persona + tools (add yours here)
- \`src/telegram/bridge.ts\` — the poller: owner lock, whitelist, groups, approvals
- \`src/telegram/api.ts\` + \`md.ts\` — Bot API wrapper; your markdown renders as Telegram formatting
- \`src/approvals.ts\` — "always allow" rules saved when you reply \`always\` to an approval prompt
- \`src/index.ts\` — \`--telegram\`, terminal, and \`--task-file <path>\` one-shot mode (other agents can delegate)

Approvals: tools that set \`needsApproval\` pause and send allow/deny/always buttons. Reply \`always\` to save a rule; \`/approvals\` lists them, \`/unallow N\` removes one.

Provider key: \`${info.envKey}\` goes in \`.env\`. Run \`${run('doctor')}\` if something does not work.

## Troubleshooting

- \`This request requires more credits, or fewer max_tokens\` (OpenRouter and other credit-metered providers): the account cannot afford the model's full output limit. \`src/agent.ts\` caps replies with \`modelSettings: { maxTokens: 4096 }\`; lower it, or add credits and raise it.

Docs: https://lousho.com/quickstart
`;
}

