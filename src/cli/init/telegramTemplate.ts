function agentSource(config: ProjectConfig, bot: BotOptions): string {
  const info = providerInfo(config.provider);
  const persona = bot.persona?.trim() || 'a helpful assistant that lives on Telegram';
  const lines = [
    "import { createAgent, defineTool, type CreateAgentConfig, type LLMProvider } from 'lousho';",
    "import { z } from 'zod';",
    '',
    '/** An example tool: the model calls it when it needs the current date or time. */',
    'export const currentTime = defineTool({',
    "  name: 'current_time',",
    "  description: 'Get the current date and time, optionally in an IANA time zone.',",
    '  input: z.object({',
    '    timeZone: z.string().optional().describe(\'IANA time zone, e.g. "Europe/Paris". Defaults to UTC.\'),',
    '  }),',
    "  execute: async ({ timeZone }) => ({ now: new Date().toLocaleString('en-US', { timeZone: timeZone ?? 'UTC' }) }),",
    '});',
    '',
    `const BOT = process.env.BOT_NAME ?? ${JSON.stringify(bot.name?.trim() || 'Bot')};`,
    `const persona = ${JSON.stringify(persona)};`,
    '',
    'const instructions = [',
    '  `You are ${BOT}, ${persona}.`,',
    "  'You talk over Telegram — short, natural messages, plain text the way people actually text. Markdown renders for you: bold, italic, code spans, bullets, links. Never say you are an AI. The owner is whoever claimed this bot first; other chats may reach you in groups or through the whitelist — answer them, but approvals and dangerous tools are the owner\\'s call.',",
    "].join('\\n\\n');",
    '',
    'const tools = [currentTime];',
    '// Caps each reply so a first run works on a low-credit key (providers such as OpenRouter reserve the',
    "// model's full output limit up front). Raise it when you need longer answers.",
    'const modelSettings = { maxTokens: 4096 };',
    '',
    '/**',
    ' * The agent\'s options. The default export is what `lousho dev src/agent.ts`',
    ' * (and `lousho chat`, `mcp`, `acp`, `build`) serve.',
    ' */',
    `const config: CreateAgentConfig = { model: '${config.provider}/${info.defaultModel}', instructions, tools, modelSettings };`,
    'export default config;',
    '',
    '/**',
    ' * The agent. `createAgent({ model, instructions })` is the whole idea; the',
    ' * optional `provider` lets tests swap in a scripted model (see agent.test.ts).',
    ' */',
    'export function buildAgent(provider?: LLMProvider) {',
    '  return provider ? createAgent({ provider, instructions, tools, modelSettings }) : createAgent(config);',
    '}',
    '',
  ];
  return lines.join('\n');
}

function testSource(): string {
  return `import { describe, expect, it } from 'vitest';
import { mockModel } from 'lousho/testing';
import { buildAgent } from './agent.js';

// mockModel scripts the model turn by turn: no network and no API key needed.
describe('agent', () => {
  it('replies with the scripted answer', async () => {
    const model = mockModel(['Hello from the mock model!']);

    const { text } = await buildAgent(model).send('Hi');

    expect(text).toBe('Hello from the mock model!');
    model.assertExhausted();
  });

  it('calls the current_time tool and answers with its result', async () => {
    const model = mockModel([
      { toolCalls: [{ name: 'current_time', args: { timeZone: 'UTC' } }] },
      { text: 'It is time for lunch.' },
    ]);

    const { text } = await buildAgent(model).send('What time is it?');

    expect(text).toBe('It is time for lunch.');
    expect(model.calls).toHaveLength(2);
    expect(model.calls[1]?.messages.at(-1)).toMatchObject({ role: 'tool', toolCallId: 'call_1' });
  });
});
`;
}

