const APPROVALS_TS = [
  '/**',
  ' * "Always allow" rules: when the bot asks approval for a tool call, a saved',
  ' * matching rule resolves it without pinging. Stored in .lousho/approvals.json.',
  ' */',
  "import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';",
  "import { dirname } from 'node:path';",
  '',
  'export interface ApprovalRule {',
  '  tool: string;',
  '  /** Optional substring an arg must contain (e.g. a command prefix). */',
  '  scope?: string;',
  '}',
  '',
  "const FILE = '.lousho/approvals.json';",
  '',
  'export function loadRules(): ApprovalRule[] {',
  '  try {',
  "    return JSON.parse(readFileSync(FILE, 'utf8'));",
  '  } catch {',
  '    return [];',
  '  }',
  '}',
  '',
  'export function saveRules(rules: ApprovalRule[]): void {',
  '  mkdirSync(dirname(FILE), { recursive: true });',
  '  writeFileSync(FILE, JSON.stringify(rules, null, 2));',
  '}',
  '',
  '/** True when a saved rule covers this tool call — auto-approve without asking. */',
  'export function findMatch(tool: string, args: Record<string, unknown>): boolean {',
  '  return loadRules().some((r) => {',
  '    if (r.tool !== tool) return false;',
  '    if (!r.scope) return true;',
  '    return JSON.stringify(args).includes(r.scope);',
  '  });',
  '}',
  '',
  'export function addRule(tool: string, args?: Record<string, unknown>): ApprovalRule {',
  "  const scope = typeof args?.cmd === 'string' ? String(args.cmd).split(' ')[0] : undefined;",
  '  const rule: ApprovalRule = { tool, ...(scope ? { scope } : {}) };',
  '  saveRules([...loadRules(), rule]);',
  '  return rule;',
  '}',
  '',
  'export function removeRule(index: number): ApprovalRule | undefined {',
  '  const rules = loadRules();',
  '  if (index < 0 || index >= rules.length) return undefined;',
  '  const [removed] = rules.splice(index, 1);',
  '  saveRules(rules);',
  '  return removed;',
  '}',
  '',
  'export const describeRule = (r: ApprovalRule, i: number) => `${i + 1}. ${r.tool}${r.scope ? ` when args contain "${r.scope}"` : \' (all calls)\'}`;',
  '',
].join('\n');

const BRIDGE_TS = [
  '/**',
  ' * Long-polling Telegram bridge. One process per bot token — a second poller',
  ' * makes Telegram return "Conflict: terminated by other getUpdates request".',
  ' *',
  ' * Access model:',
  ' *  - the FIRST chat that messages the bot becomes the owner (persisted),',
  ' *  - ALLOWED_CHATS="id1,id2" whitelists other chats,',
  ' *  - in groups (ALLOW_GROUPS=true) it answers @mentions and replies only,',
  ' *  - everyone else is logged and ignored — this bot can run tools on your',
  ' *    machine, strangers must not get turns.',
  ' */',
  "import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';",
  "import { basename, dirname, join } from 'node:path';",
  "import type { Agent, Session } from 'lousho';",
  'import {',
  '  answerCallbackQuery,',
  '  downloadFile,',
  '  editMessageMarkup,',
  '  getUpdates,',
  '  sendChatAction,',
  '  sendMessage,',
  '  type TgCallbackQuery,',
  '  type TgMessage,',
  '  type TgUpdate,',
  "} from './api.js';",
  "import { addRule, describeRule, findMatch, loadRules, removeRule } from '../approvals.js';",
  '',
  "const STATE_FILE = '.lousho/state.json';",
  "const INBOX = '.lousho/inbox';",
  'const ensureDir = (p: string) => (mkdirSync(p, { recursive: true }), p);',
  'const STARTED_AT = Date.now();',
  '',
  'interface BridgeState {',
  '  ownerChatId?: number;',
  '  ownerUserId?: number;',
  '}',
  'const loadState = (): BridgeState => {',
  '  try {',
  "    return JSON.parse(readFileSync(STATE_FILE, 'utf8'));",
  '  } catch {',
  '    return {};',
  '  }',
  '};',
  'const saveState = (patch: BridgeState) => {',
  '  ensureDir(dirname(STATE_FILE));',
  '  writeFileSync(STATE_FILE, JSON.stringify({ ...loadState(), ...patch }));',
  '};',
  '',
  "const botUsername = () => process.env.BOT_USERNAME ?? '';",
  "const groupsAllowed = () => /^true$/i.test(process.env.ALLOW_GROUPS ?? '');",
  'const allowedChats = () =>',
  "  (process.env.ALLOWED_CHATS ?? '')",
  "    .split(',')",
  '    .map((s) => Number(s.trim()))',
  '    .filter((n) => Number.isFinite(n) && n !== 0);',
  '',
  '/** Who may talk in DMs: the owner or a whitelisted chat ID. */',
  'const chatAllowed = (chatId: number) => {',
  '  const { ownerChatId } = loadState();',
  '  return chatId === ownerChatId || allowedChats().includes(chatId);',
  '};',
  '',
  '/** In groups the bot only speaks when @mentioned or replied to. */',
  'function groupTrigger(msg: TgMessage): boolean {',
  "  const text = msg.text ?? msg.caption ?? '';",
  '  const name = botUsername();',
  '  return (name.length > 0 && text.includes(`@${name}`)) || msg.reply_to_message?.from?.username === name;',
  '}',
  '',
  'const sessions = new Map<number, Session>();',
  'const sessionFor = (agent: Agent, chatId: number) => {',
  '  let s = sessions.get(chatId);',
  '  if (!s) {',
  '    s = agent.session({ id: `tg-${chatId}` });',
  '    sessions.set(chatId, s);',
  '  }',
  '  return s;',
  '};',
  '',
  '// Serializes turns per chat — sessions are stateful, two concurrent turns corrupt order.',
  'const queues = new Map<number, Promise<void>>();',
  'function enqueue(chatId: number, work: () => Promise<void>) {',
  '  const prev = queues.get(chatId) ?? Promise.resolve();',
  '  const next = prev.then(work, work);',
  '  queues.set(chatId, next.catch(() => {}));',
  '  void next;',
  '}',
  '',
  'const pendingApprovals = new Map<number, string>(); // chatId → approvalId',
  '',
  "async function resolvePending(agent: Agent, chatId: number, verdict: 'allow' | 'deny' | 'always'): Promise<boolean> {",
  '  const id = pendingApprovals.get(chatId);',
  '  if (!id) return false;',
  '  const pending = await agent.approvals.get(id);',
  "  if (verdict === 'always' && pending) {",
  '    const rule = addRule(pending.toolName, pending.args as Record<string, unknown>);',
  '    await sendMessage(chatId, `got it — auto-allowing ${describeRule(rule, 0).slice(3)} from now on. /approvals manages these.`);',
  '  }',
  '  pendingApprovals.delete(chatId);',
  "  const result = await agent.approvals.resolve({ id, approved: verdict !== 'deny' });",
  '  if (result?.text) await sendMessage(chatId, result.text);',
  '  return true;',
  '}',
  '',
  'function approvalPrompt(toolName: string, args: Record<string, unknown>): string {',
  "  const show = (v: unknown) => String(v ?? '').slice(0, 300);",
  '  const bits = Object.entries(args).map(([k, v]) => `${k}: ${show(v)}`).join(\'\\n\');',
  '  return `i want to run ${toolName}${bits ? `:\\n\\n${bits}` : \'\'}`;',
  '}',
  '',
  "async function finishTurn(agent: Agent, chatId: number, result: { text?: string | null; finishReason?: string; approvalId?: string }) {",
  '  if (result.text?.trim()) await sendMessage(chatId, result.text);',
  "  if (result.finishReason === 'awaiting-approval' && result.approvalId) {",
  '    const pending = await agent.approvals.get(result.approvalId);',
  "    const toolName = pending?.toolName ?? '?';",
  '    const args = (pending?.args ?? {}) as Record<string, unknown>;',
  '    if (findMatch(toolName, args)) {',
  '      const r = await agent.approvals.resolve({ id: result.approvalId, approved: true });',
  '      if (r?.text) await sendMessage(chatId, r.text);',
  '      return;',
  '    }',
  '    pendingApprovals.set(chatId, result.approvalId);',
  '    const id = result.approvalId;',
  '    await sendMessage(chatId, `${approvalPrompt(toolName, args)}\\n\\nallow or deny?`, {',
  '      reply_markup: {',
  '        inline_keyboard: [[',
  "          { text: 'allow', callback_data: `ap:${id}:a` },",
  "          { text: 'deny', callback_data: `ap:${id}:d` },",
  "          { text: 'always', callback_data: `ap:${id}:w` },",
  '        ]],',
  '      },',
  '    });',
  '  }',
  '}',
  '',
  'async function runTurn(agent: Agent, chatId: number, input: Parameters<Session[\'send\']>[0]) {',
  "  void sendChatAction(chatId, 'typing').catch(() => {});",
  '  return sessionFor(agent, chatId).send(input);',
  '}',
  '',
  'async function handleCommand(agent: Agent, chatId: number, text: string): Promise<boolean> {',
  '  const [cmd] = text.split(/\\s/, 1);',
  '  switch (cmd) {',
  "    case '/start':",
  '      await sendMessage(chatId, "online. first chat locks as owner — that\'s you.");',
  '      return true;',
  "    case '/status': {",
  '      const up = Math.round((Date.now() - STARTED_AT) / 60_000);',
  '      const { ownerChatId } = loadState();',
  '      await sendMessage(chatId, [',
  "        'status: up',",
  '        `up: ${up < 60 ? `${up} min` : `${Math.floor(up / 60)}h ${up % 60}m`}`,',
  "        `owner chat: ${ownerChatId ?? 'not locked yet'}`,",
  "        `allowed chats: ${allowedChats().join(', ') || 'none'}`,",
  '        `pending approvals: ${pendingApprovals.size}`,',
  "      ].join('\\n'));",
  '      return true;',
  '    }',
  "    case '/approvals': {",
  '      const rules = loadRules();',
  '      await sendMessage(',
  '        chatId,',
  '        rules.length',
  '          ? `auto-allow rules:\\n${rules.map(describeRule).join(\'\\n\')}\\n\\nreply /unallow <number> to remove one`',
  '          : \'no auto-allow rules yet — reply "always" when i ask for permission and i\\\'ll save one\',',
  '      );',
  '      return true;',
  '    }',
  "    case '/unallow': {",
  '      const n = Number(text.split(/\\s+/)[1]);',
  '      const removed = Number.isFinite(n) ? removeRule(n - 1) : undefined;',
  '      await sendMessage(chatId, removed ? `removed auto-allow for ${removed.tool}` : \'usage: /unallow <number from /approvals>\');',
  '      return true;',
  '    }',
  "    case '/help':",
  "      await sendMessage(chatId, '/start /status /approvals /unallow — otherwise just talk. Send photos and files, i can see them.');",
  '      return true;',
  '    default:',
  '      return false;',
  '  }',
  '}',
  '',
  'async function handleMessage(agent: Agent, msg: TgMessage): Promise<void> {',
  '  const chatId = msg.chat.id;',
  "  const isGroup = msg.chat.type === 'group' || msg.chat.type === 'supergroup';",
  '  const { ownerChatId } = loadState();',
  '',
  '  // Owner lock: the first private chat claims the bot. Everyone else needs',
  '  // ALLOWED_CHATS (DMs) or a group trigger.',
  '  if (isGroup) {',
  '    if (!groupsAllowed() || !groupTrigger(msg)) return;',
  '  } else if (!ownerChatId) {',
  '    saveState({ ownerChatId: chatId, ...(msg.from?.id ? { ownerUserId: msg.from.id } : {}) });',
  '  } else if (!chatAllowed(chatId)) {',
  '    console.log(`[bridge] ignored message from non-owner chat ${chatId}`);',
  '    return;',
  '  }',
  '',
  '  const session = sessionFor(agent, chatId);',
  "  const name = msg.from?.first_name ?? msg.from?.username ?? 'there';",
  '  const from = isGroup ? `[${name} in a group chat]: ` : \'\';',
  '',
  '  try {',
  '    if (msg.photo?.length) {',
  '      const photo = msg.photo[msg.photo.length - 1]!;',
  '      const { bytes, path } = await downloadFile(photo.file_id);',
  '      const file = join(ensureDir(INBOX), `tg-${msg.message_id}-${basename(path)}`);',
  '      writeFileSync(file, bytes);',
  '      const result = await runTurn(agent, chatId, [',
  "        { type: 'text', text: `${from}${name} sent a photo (saved as ${basename(file)}). ${msg.caption ?? ''}` },",
  "        { type: 'image', image: bytes, mimeType: 'image/jpeg' },",
  '      ]);',
  '      await finishTurn(agent, chatId, result);',
  '      return;',
  '    }',
  '',
  '    const media = msg.document ?? msg.voice ?? msg.audio ?? msg.video ?? msg.video_note;',
  '    if (media) {',
  '      const { bytes, path } = await downloadFile(media.file_id);',
  "      const named = 'file_name' in media ? media.file_name : undefined;",
  '      const file = join(ensureDir(INBOX), `${msg.message_id}-${basename(named ?? path)}`);',
  '      writeFileSync(file, bytes);',
  "      const kind = msg.document ? 'a file' : msg.video ? 'a video' : msg.video_note ? 'a video note' : 'a voice message';",
  '      const result = await runTurn(',
  '        agent,',
  '        chatId,',
  '        `${from}${name} sent ${kind} "${basename(file)}" saved at ${file}. Caption: ${msg.caption ?? \'none\'}. Read it from disk if useful.`,',
  '      );',
  '      await finishTurn(agent, chatId, result);',
  '      return;',
  '    }',
  '',
  '    if (msg.location || msg.venue) {',
  '      const lat = msg.location?.latitude ?? msg.venue!.location.latitude;',
  '      const lng = msg.location?.longitude ?? msg.venue!.location.longitude;',
  '      const result = await runTurn(agent, chatId, `${from}${name} shared a location: lat ${lat}, lng ${lng}.`);',
  '      await finishTurn(agent, chatId, result);',
  '      return;',
  '    }',
  '',
  '    if (msg.text) {',
  "      if (msg.text.startsWith('/') && (await handleCommand(agent, chatId, msg.text))) return;",
  '      const verdict = /^\\s*(allow|deny|always)\\s*$/i.exec(msg.text)?.[1]?.toLowerCase();',
  "      if (verdict && (await resolvePending(agent, chatId, verdict as 'allow' | 'deny' | 'always'))) return;",
  '      enqueue(chatId, async () => {',
  '        try {',
  '          const result = await runTurn(agent, chatId, `${from}${msg.text!}`);',
  '          await finishTurn(agent, chatId, result);',
  '        } catch (error) {',
  '          console.error(`[bridge] turn failed for chat ${chatId}: ${error instanceof Error ? error.message : error}`);',
  "          await sendMessage(chatId, 'something glitched on my end — resend?').catch(() => {});",
  '        }',
  '      });',
  '      return;',
  '    }',
  '  } catch (error) {',
  '    console.error(`[bridge] handler failed for chat ${chatId}: ${error instanceof Error ? error.message : error}`);',
  "    await sendMessage(chatId, 'something glitched on my end — resend?').catch(() => {});",
  '  }',
  '}',
  '',
  'async function handleCallback(agent: Agent, cq: TgCallbackQuery): Promise<void> {',
  "  const m = /^ap:([^:]+):([adw])$/.exec(cq.data ?? '');",
  '  const chatId = cq.message?.chat.id;',
  '  if (!m || !chatId) return;',
  '  const [, approvalId, code] = m;',
  '  const ownerUid = loadState().ownerUserId;',
  '  if (ownerUid && cq.from.id !== ownerUid) {',
  "    await answerCallbackQuery(cq.id, 'not yours to decide').catch(() => {});",
  '    return;',
  '  }',
  '  await answerCallbackQuery(cq.id).catch(() => {});',
  '  await editMessageMarkup(chatId, cq.message!.message_id).catch(() => {});',
  "  const verdict = code === 'a' ? 'allow' : code === 'd' ? 'deny' : 'always';",
  '  pendingApprovals.set(chatId, approvalId!);',
  '  enqueue(chatId, async () => {',
  '    try {',
  '      await resolvePending(agent, chatId, verdict);',
  '    } catch (error) {',
  '      console.error(`[bridge] approval failed: ${error instanceof Error ? error.message : error}`);',
  '    }',
  '  });',
  '}',
  '',
  'export async function runBridge(agent: Agent): Promise<never> {',
  '  let offset = 0;',
  '  const name = botUsername();',
  "  console.log(`[bridge] polling Telegram${name ? ` for @${name}` : ''} updates…`);",
  '  for (;;) {',
  '    let updates: TgUpdate[] = [];',
  '    try {',
  '      updates = await getUpdates(offset);',
  '    } catch (error) {',
  '      console.error(`[bridge] getUpdates failed: ${error instanceof Error ? error.message : error} — retrying in 5s`);',
  '      await new Promise((r) => setTimeout(r, 5_000));',
  '      continue;',
  '    }',
  '    for (const update of updates) {',
  '      offset = Math.max(offset, update.update_id + 1);',
  '      if (update.callback_query) void handleCallback(agent, update.callback_query);',
  '      else if (update.message) void handleMessage(agent, update.message);',
  '    }',
  '  }',
  '}',
  '',
].join('\n');

