const MD_TS = [
  '/**',
  ' * Markdown-ish → Telegram HTML. Escapes raw HTML first, then rewrites',
  ' * the common markers the model emits. Output is always well-formed;',
  ' * senders still fall back to plain text if Telegram rejects it.',
  ' */',
  'export function mdToTelegramHtml(src: string): string {',
  "  let s = src.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');",
  "  s = s.replace(/```[^\\n]*\\n?([\\s\\S]*?)```/g, (_m, code: string) => `<pre>${code.trim()}</pre>`);",
  "  s = s.replace(/`([^`\\n]+)`/g, '<code>$1</code>');",
  "  s = s.replace(/\\*\\*([^*\\n]+)\\*\\*/g, '<b>$1</b>');",
  "  s = s.replace(/__([^_\\n]+)__/g, '<b>$1</b>');",
  "  s = s.replace(/(^|[\\s(>])\\*([^*\\n]+)\\*(?![\\w*])/g, '$1<i>$2</i>');",
  "  s = s.replace(/(^|[\\s(>])_([^_\\n]+)_(?![\\w_])/g, '$1<i>$2</i>');",
  "  s = s.replace(/~~([^~\\n]+)~~/g, '<s>$1</s>');",
  "  s = s.replace(/^#{1,6}\\s*(.+)$/gm, '<b>$1</b>');",
  '  s = s.replace(/\\[([^\\]]+)\\]\\((https?:\\/\\/[^)\\s]+)\\)/g, \'<a href="$2">$1</a>\');',
  "  s = s.replace(/^\\s*[-*]\\s+/gm, '• ');",
  '  return s;',
  '}',
  '',
].join('\n');

