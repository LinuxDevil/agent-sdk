/**
 * docker deployment adapter.
 *
 * A thin wrapper over NodeServerAdapter: scaffold() and build() delegate to
 * it (the same server.ts/agent.config.js/package.json and the same bundled
 * dist/server.js), and scaffold() additionally writes a Dockerfile (plus a
 * .dockerignore) that packages dist/ into a node:22-slim image (22 has the node:sqlite that LOUSHO_STORE=sqlite:<path> needs).
 * describe(): 'docker build -t lousho-agent . && docker run -p 3000:3000 lousho-agent'.
 * The image also owns /app/data (declared a VOLUME) for LOUSHO_STORE=sqlite:/app/data/<file>.
 *
 * The image sets HOST=0.0.0.0: inside a container, the server's default
 * 127.0.0.1 binding would be unreachable through `docker run -p`, so the
 * image explicitly opts in to all-interfaces binding (the network boundary
 * is then the container's published port, chosen by whoever runs it).
 */
import * as path from 'node:path';
import { DeploymentAdapter, DeployOptions } from '../types';
import { writeFile } from '../bundle';
import { NodeServerAdapter } from './node-server';

export const DOCKERFILE = `# Generated by \`lousho build --target=docker\`.
FROM node:22-slim
WORKDIR /app
# A package-lock.json next to package.json (run \`npm install --package-lock-only\`
# here once and commit it) makes the image reproducible: it is then installed with npm ci.
COPY package.json package-lock.json* ./
RUN if [ -f package-lock.json ]; then npm ci --omit=dev; else npm install --omit=dev; fi && npm cache clean --force
COPY dist/ ./dist/
ENV NODE_ENV=production
# Docker copies an image directory's ownership into a fresh named volume, so the
# data directory must exist and belong to node before USER node and VOLUME, or
# \`-v lousho-data:/app/data\` mounts a root-owned dir the server cannot write to.
# Point LOUSHO_STORE at it, e.g. sqlite:/app/data/lousho.db.
RUN mkdir -p /app/data && chown node:node /app/data
VOLUME /app/data
# Run as the image's unprivileged node user, not root.
USER node
# Listen on all interfaces inside the container so \`docker run -p\` can reach it.
ENV HOST=0.0.0.0
ENV PORT=3000
EXPOSE 3000
# The slim image has no curl: Node's fetch probes GET /health.
HEALTHCHECK --interval=30s --timeout=5s --start-period=10s --retries=3 \\
  CMD ["node", "-e", "fetch('http://127.0.0.1:' + (process.env.PORT || 3000) + '/health').then((r) => process.exit(r.ok ? 0 : 1), () => process.exit(1))"]
CMD ["node", "dist/server.js"]
`;

const DOCKERIGNORE = `node_modules
server.ts
agent.config.js
.env
.env.*
**/.env
**/.env.*
**/.lousho
*.tgz
`;

export const DockerAdapter: DeploymentAdapter = {
  async scaffold(agentPath: string, outDir: string, options?: DeployOptions): Promise<void> {
    await NodeServerAdapter.scaffold(agentPath, outDir, options);
    writeFile(path.join(outDir, 'Dockerfile'), DOCKERFILE);
    writeFile(path.join(outDir, '.dockerignore'), DOCKERIGNORE);
  },

  async build(outDir: string): Promise<void> {
    await NodeServerAdapter.build(outDir);
  },

  describe(): string {
    return 'docker build -t lousho-agent . && docker run -p 3000:3000 lousho-agent';
  },
};
